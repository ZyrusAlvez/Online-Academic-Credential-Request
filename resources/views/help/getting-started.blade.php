<x-faq-item question="What can I do here?">
    <p>You can request academic credentials from the UPHSL Office of the Registrar, such as a Transcript of Records, certifications, a diploma or a CAV, then pay for them and follow each request until it is ready to claim.</p>
    <p>This system only <strong>tracks</strong> your request. Your credential is a paper document: it is never sent to you by email or as a download. You claim it in person at the Office of the Registrar, or through an authorized representative.</p>
</x-faq-item>

<x-faq-item question="Who can use it?">
    <p>Current students, graduates and former students of UPHSL. You can sign up with any email address; it does not have to be a UPHSL address.</p>
</x-faq-item>

<x-faq-item question="How do I create an account?">
    <p>Sign up with your email address and a password, or choose <strong>Sign up with Google</strong> when the page offers it. A password needs at least 8 characters, with an uppercase letter, a lowercase letter, a number and a special character.</p>
    <p>You only give your name, contact number, academic information and valid ID later, on your first request. They are then saved for the next ones.</p>
</x-faq-item>

<x-faq-item question="I didn't get the email verification code.">
    <p>After signing up, we email you a 6-digit code to confirm your address; you can't make requests until you enter it.</p>
    <ul>
        <li>Check your spam or promotions folder.</li>
        <li>A code works for 10 minutes and stops after 5 wrong tries.</li>
        <li>Choose <strong>Send a new code</strong> on the verification page (once every 30 seconds). The new code replaces the old one.</li>
    </ul>
    <p>If you signed up with Google, your address is already confirmed and no code is needed.</p>
</x-faq-item>

<x-faq-item question="I forgot my password.">
    <p>Choose <strong>Forgot your password?</strong> on the log-in page and follow the link we email you. If you signed up with Google, choose <strong>Continue with Google</strong> instead.</p>
</x-faq-item>

<x-faq-item question="Can I change my email address?">
    <p>Not in the app: your email identifies your account and your requests. If you need it changed, ask the Office of the Registrar.</p>
</x-faq-item>

<x-faq-item question="It says my account has been deactivated.">
    <p>The Office of the Registrar has turned off your account, so you can't log in. Contact them to have it turned back on.</p>
</x-faq-item>

<x-faq-item question="Can I delete my account?">
    <p>No. Your requests are part of the university's permanent record of credentials, so accounts are never deleted. You can simply stop using it.</p>
</x-faq-item>
